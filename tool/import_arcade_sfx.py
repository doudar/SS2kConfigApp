"""Import Anthony's supplied SFX pack: python tool/import_arcade_sfx.py PACK_DIR.

Requires ffmpeg on PATH. Keeps source recordings untouched, converts selected
effects to mono PCM, adds short click-free fades and normalizes with headroom.
The manifest records source hashes; it makes no claim about the pack's license.
"""
import argparse
from array import array
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import wave

ROOT = Path(__file__).resolve().parents[1]
RATE = 22050
SOURCES = {
    "pickup": "Retro/coin.wav",
    "bolt": "Retro/throw.wav",
    "combo": "Retro/power_up.wav",
    "droneHit": "Retro/explosion_small.wav",
    "bossApproach": "Musical Effects/horror_sting.wav",
    "sectorClear": "Musical Effects/8_bit_positive_long.wav",
    "bossDefeat": "Retro/explosion_large.wav",
    "enemyArrive": "Other/whoosh_1.wav",
    "blasterReady": "Retro/power_up_2.wav",
    "attackWarning": "Musical Effects/8_bit_negative_quick.wav",
    "bossHit": "Materials/metal_clang.wav",
    "comboLost": "Retro/power_down.wav",
    "sectorStart": "Musical Effects/8_bit_chime_positive.wav",
    "difficultyUp": "Weapons/weapon_upgrade.wav",
    "uiSelect": "Retro/menu_blip.wav",
    "uiConfirm": "Items/item_equip.wav",
    "rideStart": "Musical Effects/8_bit_level_start.wav",
    "ridePause": "UI/toggle_off.wav",
    "rideResume": "UI/toggle_on.wav",
    "sectorSkip": "UI/cancel.wav",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pack", type=Path)
    args = parser.parse_args()
    # Check the entire selection before writing assets.
    for relative in SOURCES.values():
        if not (args.pack / relative).is_file():
            parser.error(f"Missing source: {relative}")
    manifest = {}
    for cue, relative in SOURCES.items():
        source = args.pack / relative
        raw = subprocess.run(
            ["ffmpeg", "-v", "error", "-i", str(source), "-f", "s16le",
             "-ac", "1", "-ar", str(RATE), "pipe:1"],
            check=True, capture_output=True,
        ).stdout
        samples = array("h", raw)
        if sys.byteorder != "little":
            samples.byteswap()
        milliseconds = round(len(samples) / RATE * 1000)
        count = round(milliseconds * RATE / 1000)
        samples = samples[:count]
        samples.extend([0] * (count - len(samples)))
        fade = round(RATE * .005)
        for i in range(fade):
            samples[i] = round(samples[i] * i / fade)
            samples[-1 - i] = round(samples[-1 - i] * i / fade)
        peak = max(abs(value) for value in samples)
        if peak == 0:
            raise ValueError(f"Silent source: {relative}")
        samples = array("h", (round(value * 24000 / peak) for value in samples))
        if sys.byteorder != "little":
            samples.byteswap()
        output = ROOT / "assets" / "sounds" / f"arcade_pack_{cue}.wav"
        with wave.open(str(output), "wb") as wav:
            wav.setparams((1, 2, RATE, 0, "NONE", "not compressed"))
            wav.writeframes(samples.tobytes())
        manifest[cue] = {
            "source": relative,
            "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "asset": f"sounds/{output.name}",
            "milliseconds": milliseconds,
            "sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        }
    (ROOT / "assets/sounds/arcade_pack_manifest.json").write_text(
        json.dumps({"origin": "User-supplied SFX pack", "cues": manifest}, indent=2)
        + "\n", encoding="utf-8",
    )
    dart = "// Generated by tool/import_arcade_sfx.py. Do not edit.\n"
    dart += "const arcadePackDurations = <String, int>{\n"
    dart += "".join(f"  '{cue}': {item['milliseconds']},\n" for cue, item in manifest.items())
    dart += "};\n"
    (ROOT / "lib/utils/workout/arcade/arcade_pack_audio.g.dart").write_text(dart, encoding="utf-8")
    print(f"Imported {len(manifest)} effects ({sum(i['milliseconds'] for i in manifest.values()) / 1000:.1f}s total).")


if __name__ == "__main__":
    main()
